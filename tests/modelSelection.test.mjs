import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
import { Group, Mesh, BoxGeometry, MeshStandardMaterial, Texture } from 'three';
const source = await readFile('src/twin/selection/ModelSelection.tsx', 'utf8');
const code = ts.transpile(source, { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX })
  .replace(/from ["']([^"']+)["']/g, (_, path) => `from '${import.meta.resolve(path)}'`);
const { highlightObject } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const texture = new Texture();
const material = new MeshStandardMaterial({ color: '#123456', map: texture });
const root = new Group();
const first = new Mesh(new BoxGeometry(), material);
const second = new Mesh(first.geometry, [material]);
root.add(first, second);
let texturesDisposed = 0;
let originalsDisposed = 0;
texture.addEventListener('dispose', () => texturesDisposed++);
material.addEventListener('dispose', () => originalsDisposed++);
const restore = highlightObject(root);
assert.notEqual(first.material, material);
assert.equal(first.material, second.material[0]);
assert.equal(material.color.getHexString(), '123456');
assert.equal(first.material.map, texture);
let clonesDisposed = 0;
first.material.addEventListener('dispose', () => clonesDisposed++);
restore();
assert.equal(first.material, material);
assert.equal(second.material[0], material);
assert.equal(clonesDisposed, 1);
assert.equal(texturesDisposed, 0);
assert.equal(originalsDisposed, 0);
const restoreAgain = highlightObject(root);
restoreAgain();
assert.equal(first.material, material);
console.log('Selection highlight: shared material isolation, restoration, owned-resource cleanup and re-selection passed');
