import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
let source = await readFile('src/twin/sceneSettings.ts', 'utf8');
source = source.replace(/import .*from '@\/project\/scene';/, 'const sceneConfig = { modelPath: "test.glb" };');
const code = ts.transpile(source, { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 });
const { resolveSceneConfig } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const defaults = resolveSceneConfig({ modelPath: 'a.glb', camera: { position: undefined } });
assert.equal(defaults.customView, false);
assert.equal(defaults.camera.fov, 42);
assert.equal(defaults.lighting.intensity, 2.5);
const custom = resolveSceneConfig({ modelPath: 'b.glb', camera: { position: [1, 2, 3], target: [0, 1, 0], fov: 60 }, lighting: { intensity: 0, ambientIntensity: 0 } });
assert.equal(custom.customView, true);
assert.deepEqual(custom.camera.position, [1, 2, 3]);
assert.deepEqual(custom.target, [0, 1, 0]);
assert.equal(custom.lighting.intensity, 0);
assert.equal(custom.lighting.ambientIntensity, 0);
assert.equal(custom.lighting.color, '#ffffff');
console.log('Scene settings: empty template, custom view, partial defaults and zero intensity passed');
